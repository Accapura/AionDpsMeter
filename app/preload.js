'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  state: () => ipcRenderer.invoke('get-state'),
  schedule: () => ipcRenderer.invoke('schedule-data'),
  feedUpdate: () => ipcRenderer.invoke('feed-update'),
  armory: (kind, p) => ipcRenderer.invoke('armory', kind, p),
  fights: () => ipcRenderer.invoke('fights'),
  fightsClear: () => ipcRenderer.send('fights-clear'),
  deaths: () => ipcRenderer.invoke('deaths'),
  deathsClear: () => ipcRenderer.send('deaths-clear'),
  whatsNewSeen: () => ipcRenderer.send('whats-new-seen'),
  report: () => ipcRenderer.invoke('report'),
  webhookTest: url => ipcRenderer.invoke('webhook-test', url),
  detail: id => ipcRenderer.send('detail', id),
  set: patch => ipcRenderer.send('set-settings', patch),
  win: (cmd, arg) => ipcRenderer.send('win', cmd, arg),
  open: (what, arg) => ipcRenderer.send('open', what, arg),
  reset: () => ipcRenderer.send('reset'),
  hotkeysPause: on => ipcRenderer.send('hotkeys-pause', on),
  resizeStart: () => ipcRenderer.send('resize-start'),
  resizeEnd: () => ipcRenderer.send('resize-end'),
  restartBridge: () => ipcRenderer.send('restart-bridge'),
  overlayResetSize: () => ipcRenderer.send('overlay-reset-size'),
  copy: text => ipcRenderer.send('copy-text', String(text || '').slice(0, 64)),
  share: fightId => ipcRenderer.send('share', fightId),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.send('update-install'),
  updateSkip: v => ipcRenderer.send('update-skip', v),
  testToast: () => ipcRenderer.send('test-toast'),
  toastClose: key => ipcRenderer.send('toast-close', key),
  toastAction: (key, id) => ipcRenderer.send('toast-action', key, id),
  on: (ch, fn) => ipcRenderer.on(ch, (_e, d) => fn(d)),
});
